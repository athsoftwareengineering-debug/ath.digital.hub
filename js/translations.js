// ================================================================
//  LANGUAGE HELPER FUNCTIONS
// ================================================================

function getCurrentLanguage() {
    return localStorage.getItem('app_language') || 'my';
}

function getTranslation(key, lang) {
    const currentLang = lang || getCurrentLanguage();
    const t = TRANSLATIONS[currentLang] || TRANSLATIONS['my'];
    return t[key] || key;
}

function changeLanguage(lang) {
    localStorage.setItem('app_language', lang);
    applyTranslations(lang);
    return lang;
}

function applyTranslations(lang) {
    const t = TRANSLATIONS[lang] || TRANSLATIONS['my'];
    
    // ===== 1. UPDATE DRAWER MENU =====
    const drawerItems = [
        { selector: '.drawer-menu li:nth-child(1) a span', key: 'home' },
        { selector: '.drawer-menu li:nth-child(2) a span', key: 'plans' },
        { selector: '.drawer-menu li:nth-child(3) a span', key: 'orders' },
        { selector: '.drawer-menu li:nth-child(4) a span', key: 'live' },
        { selector: '.drawer-menu li:nth-child(5) a span', key: 'profile' },
        { selector: '.drawer-menu li:nth-child(11) a span', key: 'exportOrders' },
        { selector: '.drawer-menu li:nth-child(12) a span', key: 'support' },
        { selector: '.drawer-menu li:nth-child(14) a span', key: 'logout' }
    ];
    drawerItems.forEach(item => {
        const el = document.querySelector(item.selector);
        if (el) el.textContent = t[item.key];
    });
    
    // ===== 2. DRAWER LANGUAGE SECTION =====
    const langSection = document.querySelector('.drawer-language-section span');
    if (langSection) langSection.textContent = t.language;
    
    const langButtons = document.querySelectorAll('.drawer-language-buttons button');
    if (langButtons.length >= 3) {
        langButtons[0].textContent = '🇲🇲 ' + t.myanmar;
        langButtons[1].textContent = '🇬🇧 ' + t.english;
        langButtons[2].textContent = '🇨🇳 ' + t.chinese;
    }
    
    // ===== 3. BOTTOM NAV =====
    const navItems = document.querySelectorAll('.bottom-nav .nav-item');
    const navKeys = ['home', 'plans', 'orders', 'live', 'chat'];
    navItems.forEach((item, index) => {
        if (index < navKeys.length) {
            const span = item.querySelector('span');
            if (span) span.textContent = t[navKeys[index]];
        }
    });
    
    // ===== 4. ORDERS TAB BUTTONS =====
    const selfBtn = document.querySelector('.orders-renew-btn.self');
    const otherBtn = document.querySelector('.orders-renew-btn.other');
    if (selfBtn) selfBtn.innerHTML = `<i class="fas fa-user"></i> ${t.buyForSelf}`;
    if (otherBtn) otherBtn.innerHTML = `<i class="fas fa-users"></i> ${t.buyForOther}`;
    
    // ===== 5. WELCOME BANNER =====
    const welcomeSpan = document.getElementById('welcomeText');
    if (welcomeSpan) welcomeSpan.textContent = t.welcome;
    
    // ===== 6. SHOP STATUS =====
    const statusText = document.getElementById('statusText');
    const statusSub = document.getElementById('statusSub');
    if (statusText && statusSub) {
        const isOpen = statusText.classList.contains('open');
        statusText.textContent = isOpen ? t.shopOpen : t.shopClosed;
        statusSub.textContent = isOpen ? `(${t.open})` : `(${t.closed})`;
    }
    
    // ===== 7. TIME LABELS =====
    const labelAm = document.getElementById('labelAm');
    const labelPm = document.getElementById('labelPm');
    if (labelAm) labelAm.textContent = `(${t.morning})`;
    if (labelPm) labelPm.textContent = `(${t.evening})`;
    
    // ===== 8. WELCOME CARD =====
    const welcomeTitle = document.querySelector('.welcome-card-title');
    const welcomeDesc = document.querySelector('.welcome-card-desc');
    // These will be updated via the promotion section
    
    // ===== 9. PROMOTION SECTION =====
    const promoText = document.querySelector('.promo-text');
    const promoDesc = document.querySelector('.promo-desc');
    if (promoText) promoText.textContent = t.promotion;
    if (promoDesc) promoDesc.textContent = t.telegramJoin;
    
    // ===== 10. TELEGRAM BUTTON =====
    const telegramBtn = document.querySelector('.telegram-btn');
    if (telegramBtn) {
        const btnText = telegramBtn.querySelector('span');
        if (btnText) btnText.textContent = t.joinTelegram;
    }
    
    // ===== 11. SUPPORT MODAL =====
    const supportTitle = document.querySelector('#supportModal .modal-card h3 span');
    if (supportTitle) supportTitle.textContent = t.supportTitle;
    
    const supportClose = document.querySelector('#supportModal .support-close-btn');
    if (supportClose) supportClose.innerHTML = `<i class="fas fa-times"></i> ${t.close}`;
    
    // ===== 12. PAYMENT MODAL =====
    const paymentTitle = document.getElementById('paymentTitle');
    if (paymentTitle) paymentTitle.textContent = t.payment;
    
    const planSelectLabel = document.querySelector('#paymentModal .modal-card label[style*="font-size:0.7rem;font-weight:600;"]');
    if (planSelectLabel) planSelectLabel.innerHTML = `🎯 ${t.selectPlan} *`;
    
    const submitBtn = document.querySelector('.submit-payment');
    if (submitBtn) submitBtn.innerHTML = `✅ ${t.submitOrder}`;
    
    // ===== 13. LIVE SEARCH =====
    const searchTitle = document.querySelector('.live-search-title');
    if (searchTitle) {
        searchTitle.innerHTML = `<i class="fas fa-search"></i> ${t.search}`;
    }
    
    const searchInput = document.getElementById('liveSearchPhoneInput');
    if (searchInput) searchInput.placeholder = t.searchPlaceholder;
    
    const searchBtn = document.querySelector('.live-search-btn');
    if (searchBtn) searchBtn.innerHTML = `<i class="fas fa-search"></i> ${t.searchBtn}`;
    
    const clearBtn = document.querySelector('.live-clear-btn');
    if (clearBtn) clearBtn.innerHTML = `<i class="fas fa-times"></i> ${t.clearBtn}`;
    
    // ===== 14. LIVE HEADER =====
    const liveHeader = document.querySelector('.live-header h2');
    if (liveHeader) {
        const badge = liveHeader.querySelector('.live-badge');
        liveHeader.innerHTML = `<i class="fas fa-broadcast-tower"></i> ${t.liveOrders} ${badge ? badge.outerHTML : ''}`;
    }
    
    // ===== 15. STATUS BAR =====
    const statusCount = document.querySelector('.live-status-count');
    if (statusCount) {
        const span = statusCount.querySelector('span');
        if (span) statusCount.innerHTML = `${t.totalOrders}: <span>${span.textContent}</span>`;
    }
    
    // ===== 16. LOGOUT BUTTON =====
    const logoutBtn = document.querySelector('.logout-btn');
    if (logoutBtn) logoutBtn.innerHTML = `<i class="fas fa-sign-out-alt"></i> ${t.logout}`;
}

// ================================================================
//  EXPOSE GLOBALLY
// ================================================================

window.TRANSLATIONS = TRANSLATIONS;
window.getCurrentLanguage = getCurrentLanguage;
window.getTranslation = getTranslation;
window.changeLanguage = changeLanguage;
window.applyTranslations = applyTranslations;

// Auto-apply saved language on page load
document.addEventListener('DOMContentLoaded', function() {
    const savedLang = localStorage.getItem('app_language') || 'my';
    applyTranslations(savedLang);
    console.log(`🌍 Language applied: ${savedLang}`);
});
